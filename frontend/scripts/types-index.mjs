// Generates src/api/types/index.ts re-exporting all ts-rs generated types.
import { readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'api', 'types');
const files = readdirSync(dir).filter((f) => f.endsWith('.ts') && f !== 'index.ts').sort();
const lines = files.map((f) => `export type * from './${f.replace(/\.ts$/, '')}';`);
writeFileSync(join(dir, 'index.ts'), `// Generated by scripts/types-index.mjs – do not edit.\n${lines.join('\n')}\n`);
console.log(`types/index.ts: ${files.length} types`);
