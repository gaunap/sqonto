// Generates src/api/types/index.ts re-exporting all ts-rs generated types.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'api', 'types');
const files = readdirSync(dir).filter((f) => f.endsWith('.ts') && f !== 'index.ts').sort();
const licenseHeader = '// Copyright (C) 2026 Johannes Asal\n'
  + '// SPDX-License-Identifier: AGPL-3.0-or-later\n'
  + '// See LICENSE in the project root for the full license and warranty disclaimer.\n\n';
for (const file of files) {
  const path = join(dir, file);
  const source = readFileSync(path, 'utf8');
  if (!source.replace(/\r\n/g, '\n').startsWith(licenseHeader)) {
    writeFileSync(path, licenseHeader + source);
  }
}
const lines = files.map((f) => `export type * from './${f.replace(/\.ts$/, '')}';`);
writeFileSync(join(dir, 'index.ts'), `${licenseHeader}// Generated by scripts/types-index.mjs – do not edit.\n${lines.join('\n')}\n`);
console.log(`types/index.ts: ${files.length} types`);
